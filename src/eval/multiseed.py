"""Run the whole pipeline (data -> train -> eval) over several seeds and report mean ± std.

One synthetic draw has only ~70 BEC and ~25 hard-positive test emails, so single-run numbers move
by several points between draws. Each seed regenerates the data and retrains everything; its
artifacts go to .cache/multiseed/seed_<n>/ so the main run (seed in the config) is untouched.

Outputs: reports/multiseed.md, reports/multiseed.json
Usage: python -m src.eval.multiseed --config configs/default.yaml --seeds 42 43 44 45 46
"""
from __future__ import annotations

import argparse
import contextlib
import copy
import io
import json
from pathlib import Path

import pandas as pd

from src.common.config import REPO_ROOT, load_config
from src.data.generate import generate, write_outputs
from src.eval import ood, report
from src.models import train

METRICS = {"pr_auc": ("PR-AUC", "{:.3f}", 1), "precision": ("Precision", "{:.1f}%", 100),
           "recall": ("Recall", "{:.1f}%", 100), "bec_recall": ("BEC recall", "{:.1f}%", 100),
           "hard_pos_recall": ("Hard-positive recall", "{:.1f}%", 100), "legit_fp": ("Legit flagged", "{:.1f}", 1)}


def run_seed(cfg0: dict, seed: int) -> dict:
    cfg = copy.deepcopy(cfg0)
    cfg["seed"] = seed
    base = REPO_ROOT / ".cache" / "multiseed" / f"seed_{seed}"
    cfg["paths"] = {k: str(base / k) for k in cfg0["paths"]}
    with contextlib.redirect_stdout(io.StringIO()):
        tenants, emails, intel, _, sent = generate(cfg)
        write_outputs(cfg, tenants, emails, intel, sent)
        train.run(cfg)
        metrics = report.run(cfg)
        res = ood.run(cfg)
    attacks, legit = res[res["truth"] != "legit"], res[res["truth"] == "legit"]
    metrics["ood"] = {"attacks_caught": int((attacks["action"] != "DELIVER").sum()), "attacks": len(attacks),
                      "legit_clean": int((legit["action"] == "DELIVER").sum()), "legit": len(legit),
                      "actions": res["action"].to_dict()}
    return metrics


def fmt(values: pd.Series, spec: str, scale: float) -> str:
    if values.isna().all():
        return "–"
    mean, std = values.mean() * scale, values.std(ddof=1) * scale
    return f"{spec.format(mean)} ± {spec.format(std).rstrip('%')}"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--config", default=None)
    ap.add_argument("--seeds", type=int, nargs="+", default=[42, 43, 44, 45, 46])
    args = ap.parse_args()
    cfg = load_config(args.config)

    runs = {}
    for seed in args.seeds:
        runs[seed] = run_seed(cfg, seed)
        abl = runs[seed]["ablation"]
        print(f"seed {seed}: full model PR-AUC {abl['Full model + subject features']['pr_auc']:.3f}, "
              f"cascade BEC recall {abl['Full cascade (blocked or banner)']['bec_recall']:.1%}")

    rows = [{"seed": s, "approach": a, **v} for s, m in runs.items() for a, v in m["ablation"].items()]
    long = pd.DataFrame(rows)
    order = list(runs[args.seeds[0]]["ablation"])
    table = pd.DataFrame({label: long.groupby("approach")[k].apply(lambda v, s=spec, sc=scale: fmt(v, s, sc))
                          for k, (label, spec, scale) in METRICS.items()}).reindex(order)
    extra = pd.DataFrame([{
        "seed": s,
        "cost_base": m["cost_per_mailbox_month"]["base"], "cost_stress": m["cost_per_mailbox_month"]["stress"],
        "tier2_share": m["tier_share"].get(2, m["tier_share"].get("2", 0.0)), "latency_p99": m["latency_ms"]["p99"],
        "bec_support": m["per_class"]["bec"]["support"],
        "ood_attacks_caught": m["ood"]["attacks_caught"], "ood_legit_clean": m["ood"]["legit_clean"],
    } for s, m in runs.items()])

    per_seed = long.pivot(index="approach", columns="seed", values="pr_auc").reindex(order).dropna(how="all")
    per_seed.columns = per_seed.columns.map(str)
    seeds = ", ".join(map(str, args.seeds))
    md = f"""# Multi-seed evaluation

Seeds {seeds}: each seed regenerates the synthetic data and retrains every model, then evaluates on its own
held-out last {cfg['data']['test_days']} days. Values are mean ± standard deviation over {len(args.seeds)} runs.
Hyperparameters, the gray zone and rule severities were chosen on seed {cfg['seed']}'s validation window and
kept fixed. Generated by `make multiseed`.

## Ablation

{report.table(table)}

## Other numbers

| | mean ± std |
|---|---|
| BEC emails in the test period | {fmt(extra['bec_support'], '{:.0f}', 1)} |
| Share of mail decided at Tier 2 | {fmt(extra['tier2_share'], '{:.1f}%', 100)} |
| End-to-end latency p99 (ms) | {fmt(extra['latency_p99'], '{:.1f}', 1)} |
| Cost, base case (5 emails/mailbox/day), $/mailbox/month | {fmt(extra['cost_base'], '{:.4f}', 1)} |
| Cost, stress test (120 emails/mailbox/day), $/mailbox/month | {fmt(extra['cost_stress'], '{:.4f}', 1)} |
| Out-of-distribution set: attacks caught (of {runs[args.seeds[0]]['ood']['attacks']}) | {fmt(extra['ood_attacks_caught'], '{:.1f}', 1)} |
| Out-of-distribution set: legit delivered cleanly (of {runs[args.seeds[0]]['ood']['legit']}) | {fmt(extra['ood_legit_clean'], '{:.1f}', 1)} |

## Per seed

PR-AUC per seed (the cascade rows have no single score, so they are left out):

{report.table(per_seed, {str(s): ".3f" for s in args.seeds})}
"""
    out = Path(cfg["paths"]["reports"])
    out.mkdir(parents=True, exist_ok=True)
    (out / "multiseed.md").write_text(md)
    (out / "multiseed.json").write_text(json.dumps({"seeds": args.seeds, "runs": runs}, indent=1, default=float))
    print(report.table(table))
    print(report.table(extra.set_index("seed")))
    print(f"wrote {out}/multiseed.md")


if __name__ == "__main__":
    main()
